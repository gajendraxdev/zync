//! Compiled first-party rule definitions; remote data cannot add rules or executable policy.
use super::wording::{AccountKind, KernelSetting, SshSetting};
#[derive(Clone, Copy, Debug, PartialEq)]
pub(super) enum Category {
    Kernel,
    Filesystems,
    Ssh,
    Accounts,
    Network,
    Updates,
    Services,
}
impl Category {
    /// Keep exported labels independent of rule identifier spelling.
    pub fn label(self) -> &'static str {
        match self {
            Self::Kernel => "Kernel",
            Self::Filesystems => "Filesystems",
            Self::Ssh => "SSH",
            Self::Accounts => "Accounts",
            Self::Network => "Network",
            Self::Updates => "Updates",
            Self::Services => "Services",
        }
    }
}
#[derive(Clone, Copy, Debug, PartialEq)]
pub(super) enum ApplicabilityPolicy {
    Linux,
    DebianFamily,
}
#[derive(Clone, Copy, Debug)]
pub(super) enum SshValue {
    RootLogin,
    AttemptLimit,
    Boolean,
}
#[derive(Clone, Copy, Debug)]
pub(super) enum Evaluation {
    SshPolicy(super::modules::ssh_policy::Check),
    DockerWorkload(super::modules::workloads::Check),
    Runtime(super::runtime::Check),
    ExtendedHost(super::modules::system::Check),
    Application(super::modules::applications::Check),
    KernelRange {
        setting: KernelSetting,
        minimum: u32,
        maximum: u32,
    },
    KernelObservation(KernelSetting),
    File {
        restricted: bool,
    },
    Ssh {
        field: &'static str,
        setting: SshSetting,
        kind: SshValue,
        attention_value: Option<&'static str>,
    },
    Account {
        kind: AccountKind,
        index: usize,
        accepted: u32,
    },
    EmptyPasswords,
    Listeners,
    Firewall,
    Mount,
    AptPolicy,
    PackageHealth,
    Reboot,
    Journal,
    SshService,
}
